// Hours read the way people say them: "सुबह 9 बजे", "दोपहर 2 बजे", "शाम 6 बजे",
// "रात 10 बजे", "आधी रात". Templates use them as "{start} से {end} तक",
// "{t} के आसपास", "{start} तक".
const period = (h: number): string => {
  if (h >= 5 && h < 12) return 'सुबह';
  if (h >= 12 && h < 16) return 'दोपहर';
  if (h >= 16 && h < 20) return 'शाम';
  return 'रात';
};

const h12 = (h: number): number => (h % 12 === 0 ? 12 : h % 12);

const hour = (h: number): string => (h === 0 ? 'आधी रात' : `${period(h)} ${h12(h)} बजे`);

const time = (h: number, m: number): string => `${period(h)} ${h12(h)}:${String(m).padStart(2, '0')}`;

// Always used before "की" in the templates, so the oblique "घंटे" is right for any count.
const duration = (min: number): string => `${Math.floor(min / 60)} घंटे ${min % 60} मिनट`;

