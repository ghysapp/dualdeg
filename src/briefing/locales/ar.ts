// Hours read mid-sentence as "الساعة 14:00" (Western digits, 24 h), so templates
// say "نحو {t}", "من {start} إلى {end}", "حتى {end}" without repeating "الساعة".
const hour = (h: number): string => {
  if (h === 0) return 'منتصف الليل';
  if (h === 12) return 'الظهر';
  return `الساعة ${h}:00`;
};

const time = (h: number, m: number): string => `${h}:${String(m).padStart(2, '0')}`;

// Number–noun agreement: 1 ساعة واحدة, 2 ساعتان, 3–10 ساعات, 11+ ساعة.
const count = (n: number, one: string, two: string, few: string, many: string): string => {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
};

const duration = (min: number): string => {
  const h = Math.floor(min / 60);
  const m = min % 60;
  const hours = count(h, 'ساعة واحدة', 'ساعتان', 'ساعات', 'ساعة');
  const mins = count(m, 'دقيقة واحدة', 'دقيقتان', 'دقائق', 'دقيقة');
  if (h === 0) return mins;
  if (m === 0) return hours;
  return `${hours} و${mins}`;
};

