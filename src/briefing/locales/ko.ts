// Hours read "오전 9시" / "오후 2시" / "정오" / "자정". Every template follows them
// with a particle that doesn't depend on the preceding sound (부터, 까지, 쯤, 에).
const hour = (h: number): string => {
  if (h === 0) return '자정';
  if (h === 12) return '정오';
  return h < 12 ? `오전 ${h}시` : `오후 ${h - 12}시`;
};

const time = (h: number, m: number): string => {
  const hh = h % 12 === 0 ? 12 : h % 12;
  return `${h < 12 ? '오전' : '오후'} ${hh}:${String(m).padStart(2, '0')}`;
};

const duration = (min: number): string => {
  const h = Math.floor(min / 60);
  const m = min % 60;
  return m === 0 ? `${h}시간` : `${h}시간 ${m}분`;
};

