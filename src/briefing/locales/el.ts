// Hours read as "14:00" after "στις": "γύρω στις 14:00", "από τις 14:00 έως τις 16:00".
const hour = (h: number): string => (h === 0 ? '00:00' : `${h}:00`);
const time = (h: number, m: number): string => `${h}:${String(m).padStart(2, '0')}`;
const duration = (min: number): string => {
  const h = Math.floor(min / 60);
  const m = min % 60;
  const hs = `${h} ${h === 1 ? 'ώρα' : 'ώρες'}`;
  return m === 0 ? hs : `${hs} και ${m} ${m === 1 ? 'λεπτό' : 'λεπτά'}`;
};

